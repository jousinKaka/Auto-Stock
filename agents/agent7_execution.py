"""Agent 7: Toss Securities API Execution Agent.

Executes order sheets generated by Agent 2 via Toss Securities OpenAPI,
syncs account balance and holdings, and handles Dry-Run simulation.
"""

from __future__ import annotations

import logging
import math
import os
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from pydantic import BaseModel, Field

from agents.agent2_strategy import OrderPlan, OrderType, StrategyState
from services.toss_client import TossSecuritiesClient


class ExecutionResult(BaseModel):
    timestamp: str
    ticker: str
    is_dry_run: bool
    submitted_orders_count: int
    successful_orders_count: int
    failed_orders_count: int
    orders_detail: List[Dict[str, Any]] = Field(default_factory=list)
    account_sync: Dict[str, Any] = Field(default_factory=dict)
    summary_message: str = ""


class TossExecutionAgent:
    """Agent 7: Handles broker order submission and portfolio synchronization."""

    def __init__(
        self,
        client: Optional[TossSecuritiesClient] = None,
        dry_run: bool = True,
        max_live_buy_notional_usd: Optional[float] = None,
        state_dir: Optional[Path] = None,
    ):
        self.client = client or TossSecuritiesClient()
        if not dry_run and not self.client.is_configured:
            raise RuntimeError("Live order submission requires configured Toss API credentials.")
        self.dry_run = dry_run
        self.max_live_buy_notional_usd = max_live_buy_notional_usd
        configured_state_dir = os.environ.get("AUTO_STOCK_STATE_DIR")
        self.state_dir = state_dir or Path(
            configured_state_dir or Path.home() / ".local" / "state" / "auto-stock"
        )
        self.logger = logging.getLogger("TossExecutionAgent")

    def _prepare_live_execution(self, order_plan: OrderPlan) -> None:
        limit = self.max_live_buy_notional_usd
        if limit is None or not math.isfinite(limit) or limit <= 0:
            raise ValueError("Live orders require a positive --max-live-buy-notional-usd limit.")

        buy_notional = sum(
            order.estimated_total for order in order_plan.orders if order.side.value == "BUY"
        )
        sell_quantity = sum(
            order.quantity for order in order_plan.orders if order.side.value == "SELL"
        )
        if not math.isfinite(buy_notional) or buy_notional > limit:
            raise ValueError(
                f"Planned SOXL buys total ${buy_notional:.2f}, exceeding the "
                f"${limit:.2f} live buy limit; no orders were submitted."
            )
        if any(
            order.quantity <= 0 or not math.isfinite(order.price) or order.price <= 0
            for order in order_plan.orders
        ):
            raise ValueError("Live order plan contains an invalid price or quantity.")

        for status in ("OPEN", "CLOSED"):
            cursor = None
            while True:
                result = self.client.get_order_history(
                    status=status,
                    symbol=order_plan.ticker,
                    from_date=order_plan.date if status == "CLOSED" else None,
                    to_date=order_plan.date if status == "CLOSED" else None,
                    cursor=cursor,
                    limit=100,
                )
                orders = result.get("orders")
                if not isinstance(orders, list):
                    raise RuntimeError(
                        f"Toss {status.lower()} order-history response has an invalid orders field; "
                        "no planned orders were submitted."
                    )
                if status == "OPEN" and orders:
                    raise RuntimeError(
                        "Found existing open SOXL orders; review/cancel them before live automation. "
                        "No planned orders were submitted."
                    )
                if status == "CLOSED":
                    for order in orders:
                        side = str(order.get("side", "")).upper()
                        if side not in {"BUY", "SELL"}:
                            raise RuntimeError(
                                "Toss closed-order history has an unknown order side; "
                                "no planned orders were submitted."
                            )
                        if side != "BUY":
                            continue

                        execution = order.get("execution")
                        if not isinstance(execution, dict) or "filledQuantity" not in execution:
                            raise RuntimeError(
                                "Toss closed buy order has no filled quantity; "
                                "inspect order history before retrying. No planned orders were submitted."
                            )
                        try:
                            filled_quantity = float(execution["filledQuantity"])
                        except (TypeError, ValueError) as exc:
                            raise RuntimeError(
                                "Toss closed buy order has an invalid filled quantity; "
                                "inspect order history before retrying. No planned orders were submitted."
                            ) from exc
                        if not math.isfinite(filled_quantity) or filled_quantity < 0:
                            raise RuntimeError(
                                "Toss closed buy order has an invalid filled quantity; "
                                "inspect order history before retrying. No planned orders were submitted."
                            )
                        if filled_quantity > 0:
                            raise RuntimeError(
                                f"Found a same-day filled SOXL buy order for {order_plan.date}; "
                                "no planned orders were submitted."
                            )
                if not result.get("hasNext"):
                    break
                cursor = result.get("nextCursor")
                if not cursor:
                    raise RuntimeError(
                        f"Toss {status.lower()} order-history page has no next cursor; "
                        "no planned orders were submitted."
                    )

        buying_power = self.client.get_buying_power(currency="USD")
        raw_cash = buying_power.get("cashBuyingPower", buying_power.get("usdCash"))
        if raw_cash is None:
            raise RuntimeError("Toss buying-power response has no USD cash field; no planned orders were submitted.")
        available_cash = float(raw_cash)
        if not math.isfinite(available_cash) or available_cash < buy_notional:
            raise RuntimeError(
                f"Planned SOXL buys total ${buy_notional:.2f}, exceeding available USD "
                f"buying power ${available_cash:.2f}; no orders were submitted."
            )

        holdings = self.client.get_holdings()
        items = holdings.get("items")
        if not isinstance(items, list):
            raise RuntimeError("Toss holdings response has an invalid items field; no planned orders were submitted.")
        holding = next(
            (item for item in items if item.get("symbol") == order_plan.ticker),
            None,
        )
        available_shares = int(holding.get("quantity", 0)) if holding else 0
        if sell_quantity > available_shares:
            raise RuntimeError(
                f"Planned SOXL sells total {sell_quantity} shares, exceeding current holdings "
                f"of {available_shares}; no planned orders were submitted."
            )

        lock_path = self.state_dir / f"live-{order_plan.ticker}-{order_plan.date}.lock"
        self.state_dir.mkdir(parents=True, exist_ok=True)
        try:
            lock_fd = os.open(lock_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        except FileExistsError as exc:
            raise RuntimeError(
                f"Live execution already attempted for {order_plan.ticker} on "
                f"{order_plan.date}; inspect Toss orders before removing {lock_path}."
            ) from exc
        with os.fdopen(lock_fd, "w", encoding="utf-8") as lock_file:
            lock_file.write(
                f"ticker={order_plan.ticker}\n"
                f"date={order_plan.date}\n"
                f"planned_buy_notional_usd={buy_notional:.2f}\n"
                f"planned_orders={len(order_plan.orders)}\n"
                f"created_at={datetime.now().isoformat()}\n"
            )

    def sync_account_state(self, current_state: StrategyState) -> Tuple[StrategyState, Dict[str, Any]]:
        """Synchronize strategy state with live Toss account balance and holdings."""
        sync_info = {
            "is_live_synced": False,
            "broker_usd_cash": current_state.remaining_cash,
            "broker_soxl_shares": current_state.total_shares,
            "broker_soxl_avg_price": current_state.avg_price,
            "krw_usd_rate": 1400.0,
        }

        if self.dry_run:
            sync_info["note"] = "모의 실행(Dry-Run) 모드이므로 로컬 전략 상태를 유지합니다."
            return current_state, sync_info

        try:
            # 1. Exchange Rate
            rate = self.client.get_exchange_rate()
            sync_info["krw_usd_rate"] = rate

            # 2. Buying Power (Cash)
            bp = self.client.get_buying_power(currency="USD")
            raw_cash = bp.get("cashBuyingPower", bp.get("usdCash", current_state.remaining_cash))
            usd_cash = float(raw_cash) if raw_cash is not None else float(current_state.remaining_cash)
            sync_info["broker_usd_cash"] = usd_cash
            current_state.remaining_cash = max(0.0, round(usd_cash - current_state.excluded_cash, 2))

            # 3. Stock Holdings
            holdings_resp = self.client.get_holdings()
            items = holdings_resp.get("items", [])
            soxl_item = next((it for it in items if it.get("symbol") == current_state.ticker), None)

            if soxl_item:
                soxl_qty = int(soxl_item.get("quantity", 0))
                soxl_avg = float(
                    soxl_item.get("averagePurchasePrice", soxl_item.get("averagePrice", 0.0))
                )
                sync_info["broker_soxl_shares"] = soxl_qty
                sync_info["broker_soxl_avg_price"] = soxl_avg

                current_state.total_shares = soxl_qty
                current_state.avg_price = soxl_avg
            else:
                sync_info["broker_soxl_shares"] = 0
                sync_info["broker_soxl_avg_price"] = 0.0

            sync_info["is_live_synced"] = True
            sync_info["note"] = "토스증권 실계좌 잔고 및 보유량이 정상 동기화되었습니다."

        except Exception as e:
            self.logger.error(f"Failed to sync with Toss Securities: {e}")
            sync_info["error"] = str(e)
            sync_info["note"] = "토스 API 계좌 동기화 중 오류가 발생하여 기존 상태를 유지합니다."

        return current_state, sync_info

    def execute_order_plan(self, order_plan: OrderPlan) -> ExecutionResult:
        """Submit the generated daily order plan to Toss Securities."""
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        submitted_details: List[Dict[str, Any]] = []
        success_count = 0
        fail_count = 0

        if not self.dry_run and order_plan.orders:
            self._prepare_live_execution(order_plan)

        for order_index, order in enumerate(order_plan.orders):
            order_detail = {
                "tag": order.tag,
                "side": order.side.value,
                "order_type": order.order_type.value,
                "price": order.price,
                "quantity": order.quantity,
                "description": order.description,
            }

            if self.dry_run:
                # Mock execution log
                order_detail["status"] = "MOCK_SUBMITTED"
                order_detail["clientOrderId"] = f"mock-{order.side.value.lower()}-{order.tag.lower()}"
                order_detail["response"] = {"success": True, "message": "Dry-run mode simulated order"}
                submitted_details.append(order_detail)
                success_count += 1
            else:
                # Live submission via Toss OpenAPI
                try:
                    # Toss represents LOC as LIMIT with CLS time-in-force.
                    mapped_type = "LIMIT" if order.order_type in [OrderType.LIMIT, OrderType.LOC] else "MARKET"
                    order_price = order.price if mapped_type == "LIMIT" else None
                    time_in_force = (
                        "CLS" if order.order_type == OrderType.LOC
                        else "DAY" if order.order_type == OrderType.LIMIT
                        else None
                    )

                    resp = self.client.create_order(
                        symbol=order_plan.ticker,
                        side=order.side.value,
                        order_type=mapped_type,
                        quantity=order.quantity,
                        price=order_price,
                        client_order_id=f"as-{order_plan.date.replace('-', '')}-{order_index:02d}",
                        time_in_force=time_in_force,
                    )
                    order_detail["status"] = "LIVE_SUBMITTED"
                    order_detail["response"] = resp
                    submitted_details.append(order_detail)
                    success_count += 1
                except Exception as e:
                    self.logger.error(f"Failed to submit order {order.tag}: {e}")
                    order_detail["status"] = "FAILED"
                    order_detail["error"] = str(e)
                    submitted_details.append(order_detail)
                    fail_count += 1
                    if not self.dry_run:
                        break

        mode_str = "[모의실행/Dry-Run]" if self.dry_run else "[실거래/Live]"
        summary = (
            f"{mode_str} 총 {len(order_plan.orders)}건의 주문 중 "
            f"{success_count}건 접수 완료, {fail_count}건 실패."
        )

        return ExecutionResult(
            timestamp=now_str,
            ticker=order_plan.ticker,
            is_dry_run=self.dry_run,
            submitted_orders_count=len(order_plan.orders),
            successful_orders_count=success_count,
            failed_orders_count=fail_count,
            orders_detail=submitted_details,
            summary_message=summary,
        )
