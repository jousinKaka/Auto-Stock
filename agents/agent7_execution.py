"""Agent 7: Toss Securities API Execution Agent.

Executes order sheets generated by Agent 2 via Toss Securities OpenAPI,
syncs account balance and holdings, and handles Dry-Run simulation.
"""

from __future__ import annotations

import logging
from datetime import datetime
from typing import Any, Dict, List, Optional, Tuple
from pydantic import BaseModel, Field

from agents.agent2_strategy import OrderLine, OrderPlan, OrderSide, OrderType, StrategyState
from services.toss_client import TossSecuritiesClient


class ExecutionResult(BaseModel):
    timestamp: str
    ticker: str
    is_dry_run: bool
    submitted_orders_count: int
    successful_orders_count: int
    failed_orders_count: int
    orders_detail: List[Dict[str, Any]] = Field(default_factory=list)
    account_sync: Dict[str, Any] = Field(default_factory=dict)
    summary_message: str = ""


class TossExecutionAgent:
    """Agent 7: Handles broker order submission and portfolio synchronization."""

    def __init__(self, client: Optional[TossSecuritiesClient] = None, dry_run: bool = True):
        self.client = client or TossSecuritiesClient()
        # Default to dry_run unless explicitly disabled and credentials valid
        self.dry_run = dry_run or not self.client.is_configured
        self.logger = logging.getLogger("TossExecutionAgent")

    def sync_account_state(self, current_state: StrategyState) -> Tuple[StrategyState, Dict[str, Any]]:
        """Synchronize strategy state with live Toss account balance and holdings."""
        sync_info = {
            "is_live_synced": False,
            "broker_usd_cash": current_state.remaining_cash,
            "broker_soxl_shares": current_state.total_shares,
            "broker_soxl_avg_price": current_state.avg_price,
            "krw_usd_rate": 1400.0,
        }

        if self.dry_run:
            sync_info["note"] = "모의 실행(Dry-Run) 모드이므로 로컬 전략 상태를 유지합니다."
            return current_state, sync_info

        try:
            # 1. Exchange Rate
            rate = self.client.get_exchange_rate()
            sync_info["krw_usd_rate"] = rate

            # 2. Buying Power (Cash)
            bp = self.client.get_buying_power(currency="USD")
            raw_cash = bp.get("cashBuyingPower", bp.get("usdCash", current_state.remaining_cash))
            usd_cash = float(raw_cash) if raw_cash is not None else float(current_state.remaining_cash)
            sync_info["broker_usd_cash"] = usd_cash
            current_state.remaining_cash = usd_cash

            # 3. Stock Holdings
            holdings_resp = self.client.get_holdings()
            items = holdings_resp.get("items", [])
            soxl_item = next((it for it in items if it.get("symbol") == current_state.ticker), None)

            if soxl_item:
                soxl_qty = int(soxl_item.get("quantity", 0))
                soxl_avg = float(soxl_item.get("averagePrice", 0.0))
                sync_info["broker_soxl_shares"] = soxl_qty
                sync_info["broker_soxl_avg_price"] = soxl_avg

                current_state.total_shares = soxl_qty
                current_state.avg_price = soxl_avg
            else:
                sync_info["broker_soxl_shares"] = 0
                sync_info["broker_soxl_avg_price"] = 0.0

            sync_info["is_live_synced"] = True
            sync_info["note"] = "토스증권 실계좌 잔고 및 보유량이 정상 동기화되었습니다."

        except Exception as e:
            self.logger.error(f"Failed to sync with Toss Securities: {e}")
            sync_info["error"] = str(e)
            sync_info["note"] = "토스 API 계좌 동기화 중 오류가 발생하여 기존 상태를 유지합니다."

        return current_state, sync_info

    def execute_order_plan(self, order_plan: OrderPlan) -> ExecutionResult:
        """Submit the generated daily order plan to Toss Securities."""
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        submitted_details: List[Dict[str, Any]] = []
        success_count = 0
        fail_count = 0

        for order in order_plan.orders:
            order_detail = {
                "tag": order.tag,
                "side": order.side.value,
                "order_type": order.order_type.value,
                "price": order.price,
                "quantity": order.quantity,
                "description": order.description,
            }

            if self.dry_run:
                # Mock execution log
                order_detail["status"] = "MOCK_SUBMITTED"
                order_detail["clientOrderId"] = f"mock-{order.side.value.lower()}-{order.tag.lower()}"
                order_detail["response"] = {"success": True, "message": "Dry-run mode simulated order"}
                submitted_details.append(order_detail)
                success_count += 1
            else:
                # Live submission via Toss OpenAPI
                try:
                    # In Toss OpenAPI, LOC ceiling price maps to LIMIT order
                    mapped_type = "LIMIT" if order.order_type in [OrderType.LIMIT, OrderType.LOC] else "MARKET"
                    order_price = order.price if mapped_type == "LIMIT" else None

                    resp = self.client.create_order(
                        symbol=order_plan.ticker,
                        side=order.side.value,
                        order_type=mapped_type,
                        quantity=order.quantity,
                        price=order_price,
                        client_order_id=f"soxl-{order.tag.lower()[:10]}-{datetime.now().strftime('%m%d%H%M%S')}",
                    )
                    order_detail["status"] = "LIVE_SUBMITTED"
                    order_detail["response"] = resp
                    submitted_details.append(order_detail)
                    success_count += 1
                except Exception as e:
                    self.logger.error(f"Failed to submit order {order.tag}: {e}")
                    order_detail["status"] = "FAILED"
                    order_detail["error"] = str(e)
                    submitted_details.append(order_detail)
                    fail_count += 1

        mode_str = "[모의실행/Dry-Run]" if self.dry_run else "[실거래/Live]"
        summary = (
            f"{mode_str} 총 {len(order_plan.orders)}건의 주문 중 "
            f"{success_count}건 접수 완료, {fail_count}건 실패."
        )

        return ExecutionResult(
            timestamp=now_str,
            ticker=order_plan.ticker,
            is_dry_run=self.dry_run,
            submitted_orders_count=len(order_plan.orders),
            successful_orders_count=success_count,
            failed_orders_count=fail_count,
            orders_detail=submitted_details,
            summary_message=summary,
        )

